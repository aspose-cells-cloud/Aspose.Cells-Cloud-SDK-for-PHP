namespace Aspose\Cells\Cloud\Editor;

/**
 * One worksheet returned by {@see Editor::list_worksheets()}.
 */
class Worksheet
{
    /** @var string */
    public $name;

    /** @var string */
    public $type;

    /**
     * @param string $name worksheet name
     * @param string $type sheet type (e.g. "Worksheet")
     */
    public function __construct($name = '', $type = '')
    {
        $this->name = $name;
        $this->type = $type;
    }

    /**
     * @return string
     */
    public function getName()
    {
        return $this->name;
    }

    /**
     * @return string
     */
    public function getType()
    {
        return $this->type;
    }
}
